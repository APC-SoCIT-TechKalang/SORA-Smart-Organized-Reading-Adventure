-- Canonical PostgreSQL schema for the revised S.O.R.A. ERD.
begin;

create schema if not exists sora_v2;

create table sora_v2.authors (
  author_id integer generated by default as identity primary key,
  author_firstname varchar(255) not null,
  author_lastname varchar(255) not null
);

create table sora_v2.books (
  book_id integer generated by default as identity primary key,
  author_id integer not null references sora_v2.authors(author_id),
  dewey_decimal varchar(30),
  title varchar(255) not null,
  original_title text,
  romanized_title text,
  isbn varchar(50) unique,
  volume_number integer,
  publisher text,
  imprint text,
  book_type text not null check (book_type in ('Manga', 'Light Novel', 'Adult Manga')),
  book_description text,
  coverimage_url text,
  age_rating integer not null,
  book_genre varchar(100) default 'General',
  created_at timestamptz not null default now()
);

create table sora_v2.book_copies (
  copy_id integer generated by default as identity primary key,
  book_id integer not null references sora_v2.books(book_id),
  copy_number integer not null,
  copy_status text not null default 'In-Shelf'
    check (copy_status in ('In-Shelf', 'With Reader', 'In Return Cart')),
  barcode varchar(50) not null unique,
  unique (book_id, copy_number)
);

create table sora_v2.users (
  id uuid primary key default gen_random_uuid(),
  first_name varchar(255) not null,
  middle_name varchar(255),
  last_name varchar(255) not null,
  username varchar(100) not null unique,
  password_hash varchar(255),
  birthdate date not null,
  user_role text not null check (user_role in ('Reader', 'Librarian')),
  mobile_number varchar(255) not null unique,
  is_active boolean not null default true,
  deactivated_at timestamptz,
  membership_type text check (membership_type in ('Guild Member', 'Guild Adventurer', 'Wanderer')),
  membership_rank varchar(50),
  membership_status text not null default 'INACTIVE'
    check (membership_status in ('INACTIVE', 'ACTIVE', 'EXPIRED', 'SUSPENDED')),
  remaining_minutes integer not null default 0 check (remaining_minutes >= 0),
  membership_started_at timestamptz,
  membership_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (is_active or deactivated_at is not null),
  check (membership_status <> 'ACTIVE' or
    (membership_type is not null and membership_rank is not null
      and membership_expires_at is not null))
);

create table sora_v2.librarycard (
  librarycard_id uuid primary key default gen_random_uuid(),
  user_id uuid not null references sora_v2.users(id),
  librarycard_rfid varchar(50) unique,
  created_at timestamptz not null default now(),
  is_active boolean not null default true,
  deactivated_at timestamptz
);

create table sora_v2.seats (
  seat_id integer generated by default as identity primary key,
  seat_number integer not null,
  seat_area varchar(255) not null,
  seat_status varchar(255) default 'AVAILABLE'
);

create table sora_v2.rewards (
  reward_id integer generated by default as identity primary key,
  reward_name varchar(255) not null,
  points_cost integer not null,
  stock_quantity integer not null,
  is_available boolean not null
);

create table sora_v2.topup_transactions (
  topup_id integer generated by default as identity primary key,
  processed_by uuid not null references sora_v2.users(id),
  user_id uuid not null references sora_v2.users(id),
  minutes_added integer not null,
  payment_status text not null default 'UNPAID' check (payment_status in ('UNPAID', 'PAID')),
  amount_paid numeric(10,2) not null,
  payment_method text not null check (payment_method in ('Cash', 'Gcash', 'Card')),
  payment_reference varchar(100),
  created_at timestamptz not null default now()
);

create table sora_v2.sessions (
  session_id integer generated by default as identity primary key,
  user_id uuid not null references sora_v2.users(id),
  copy_id integer not null references sora_v2.book_copies(copy_id),
  seat_id integer not null references sora_v2.seats(seat_id),
  borrow_date timestamptz default now(),
  return_date timestamptz,
  assigned_at timestamptz not null default now(),
  released_at timestamptz,
  session_status text not null default 'READING'
    check (session_status in ('READING', 'CHECKOUT PENDING', 'CLOSED')),
  food_charge numeric(10,2) not null default 0,
  other_charge numeric(10,2) not null default 0,
  food_other_charges_payment text not null default 'UNPAID'
    check (food_other_charges_payment in ('UNPAID', 'PAID')),
  food_other_payment_method text check (food_other_payment_method in ('Cash', 'Gcash', 'Card')),
  food_other_payment_reference varchar(100),
  paid_at timestamptz,
  checked_in_at timestamptz,
  checked_out_at timestamptz
);

create table sora_v2.session_activity_logs (
  log_id integer generated by default as identity primary key,
  session_id integer references sora_v2.sessions(session_id),
  user_id uuid references sora_v2.users(id),
  book_id integer references sora_v2.books(book_id),
  copy_id integer references sora_v2.book_copies(copy_id),
  action varchar(100) not null,
  details text,
  created_at timestamptz not null default now()
);

create table sora_v2.quests (
  quest_id integer generated by default as identity primary key,
  quest_name varchar(255) not null,
  quest_difficulty varchar(255) not null,
  quest_description varchar(255) not null,
  quest_requirement varchar(255) not null,
  target_genre varchar(100),
  time_limit_days integer,
  reviewed_by uuid references sora_v2.users(id),
  review_decision text not null default 'PENDING'
    check (review_decision in ('PENDING', 'VERIFIED', 'REJECTED')),
  previous_parameters json,
  revised_parameters json,
  points_reward integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table sora_v2.user_quests (
  user_quest_id integer generated by default as identity primary key,
  user_id uuid not null references sora_v2.users(id),
  quest_id integer not null references sora_v2.quests(quest_id),
  progress_value integer not null default 0,
  quest_status text not null default 'IN PROGRESS'
    check (quest_status in ('IN PROGRESS', 'COMPLETED', 'EXPIRED')),
  assigned_at timestamptz not null default now(),
  deadline_at timestamptz,
  completed_at timestamptz,
  points_awarded integer not null default 0
);

create table sora_v2.redemptions (
  redemption_id integer generated by default as identity primary key,
  user_id uuid not null references sora_v2.users(id),
  reward_id integer not null references sora_v2.rewards(reward_id),
  points_spent integer not null,
  redemption_status text not null check (redemption_status in ('PENDING', 'FULFILLED', 'CANCELLED')),
  redeemed_at timestamptz not null default now()
);

create table sora_v2.ai_requests (
  request_id uuid primary key default gen_random_uuid(),
  user_id uuid not null references sora_v2.users(id),
  request_prompt text not null,
  response_text text,
  request_category text not null default 'GENERAL_LIBRARY'
    check (request_category in ('CATALOG', 'RECOMMENDATION', 'ACCOUNT_HELP',
      'QUEST_HELP', 'GENERAL_LIBRARY')),
  validation_status text not null default 'PENDING'
    check (validation_status in ('PENDING', 'ALLOWED', 'REJECTED')),
  rejection_reason varchar(255),
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  check (char_length(btrim(request_prompt)) between 1 and 2000),
  check (response_text is null or char_length(response_text) <= 4000),
  check ((validation_status = 'REJECTED' and rejection_reason is not null)
    or (validation_status <> 'REJECTED' and rejection_reason is null))
);

create table sora_v2.rank_history (
  rank_id integer generated by default as identity primary key,
  user_id uuid not null references sora_v2.users(id),
  previous_rank varchar(50),
  new_rank varchar(50) not null,
  changed_at timestamptz not null default now()
);

create function sora_v2.touch_updated_at()
returns trigger language plpgsql set search_path = sora_v2 as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
create trigger quests_touch_updated_at before update on sora_v2.quests
for each row execute function sora_v2.touch_updated_at();
create trigger users_touch_updated_at before update on sora_v2.users
for each row execute function sora_v2.touch_updated_at();

do $$
declare table_name text;
begin
  for table_name in select tablename from pg_tables where schemaname = 'sora_v2' loop
    execute format('alter table sora_v2.%I enable row level security', table_name);
  end loop;
end;
$$;
revoke all on schema sora_v2 from public, anon, authenticated;
revoke all on all tables in schema sora_v2 from public, anon, authenticated;
revoke all on all sequences in schema sora_v2 from public, anon, authenticated;

commit;
