-- Canonical ISBN handling and atomic admin catalogue creation.
begin;

create or replace function public.canonical_isbn(value text)
returns text language plpgsql immutable strict set search_path = public as $$
declare
  raw text := regexp_replace(upper(value), '[^0-9X]', '', 'g');
  total integer := 0;
  index integer;
  check_digit integer;
  isbn13 text;
begin
  if length(raw) = 10 and raw ~ '^[0-9]{9}[0-9X]$' then
    for index in 1..10 loop
      total := total + (11-index) * (case when substr(raw,index,1)='X' then 10 else substr(raw,index,1)::integer end);
    end loop;
    if total % 11 <> 0 then return null; end if;
    isbn13 := '978' || substr(raw,1,9);
    total := 0;
    for index in 1..12 loop
      total := total + substr(isbn13,index,1)::integer * (case when index % 2 = 0 then 3 else 1 end);
    end loop;
    return isbn13 || ((10-(total%10))%10)::text;
  end if;
  if length(raw) = 13 and raw ~ '^97[89][0-9]{10}$' then
    for index in 1..12 loop
      total := total + substr(raw,index,1)::integer * (case when index % 2 = 0 then 3 else 1 end);
    end loop;
    check_digit := (10-(total%10))%10;
    if check_digit = substr(raw,13,1)::integer then return raw; end if;
  end if;
  return null;
end;
$$;

-- Normalize valid legacy values. Invalid legacy values are retained for staff review.
update public.books set isbn=public.canonical_isbn(isbn)
where isbn is not null and public.canonical_isbn(isbn) is not null
  and isbn is distinct from public.canonical_isbn(isbn);

do $$
begin
  if exists(
    select public.canonical_isbn(isbn) from public.books
    where public.canonical_isbn(isbn) is not null
    group by public.canonical_isbn(isbn) having count(*) > 1
  ) then
    raise exception 'Duplicate ISBN records must be merged before applying migration 006';
  end if;
end;
$$;

create unique index if not exists books_canonical_isbn_unique
  on public.books (public.canonical_isbn(isbn))
  where public.canonical_isbn(isbn) is not null;

create table if not exists public.catalog_lookup_requests (
  request_id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  requested_at timestamptz not null default now()
);
alter table public.catalog_lookup_requests enable row level security;
revoke all on public.catalog_lookup_requests from anon, authenticated;

create or replace function public.consume_catalog_lookup()
returns boolean language plpgsql security definer set search_path = public as $$
declare request_count integer;
begin
  if not public.has_role('admin') then raise exception 'Staff access required'; end if;
  delete from public.catalog_lookup_requests where requested_at < now()-interval '10 minutes';
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text,1));
  select count(*) into request_count from public.catalog_lookup_requests
    where user_id=auth.uid() and requested_at>=now()-interval '10 minutes';
  if request_count>=20 then return false; end if;
  insert into public.catalog_lookup_requests(user_id) values(auth.uid());
  return true;
end;
$$;
revoke all on function public.consume_catalog_lookup() from public;
grant execute on function public.consume_catalog_lookup() to authenticated;

create or replace function public.admin_create_catalog_entry(
  p_book jsonb,
  p_genres text[] default '{}',
  p_barcode text default null,
  p_shelf_id bigint default null,
  p_condition_notes text default null
)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  canonical text;
  target_book_id bigint;
  created_new boolean := false;
  genre_name text;
begin
  if not public.has_role('admin') then raise exception 'Staff access required'; end if;
  if nullif(trim(p_book->>'title'),'') is null then raise exception 'Title is required'; end if;

  if nullif(trim(p_book->>'isbn'),'') is not null then
    canonical := public.canonical_isbn(p_book->>'isbn');
    if canonical is null then raise exception 'Enter a valid ISBN-10 or ISBN-13'; end if;
    perform pg_advisory_xact_lock(hashtextextended(canonical, 0));
    select book_id into target_book_id from public.books where public.canonical_isbn(isbn)=canonical limit 1;
  end if;

  if target_book_id is null then
    insert into public.books(title,original_title,romanized_title,author,contributors,isbn,series_name,volume_number,format,publisher,imprint,book_type,demographic,themes,age_rating,description,cover_image_url,acquisition_status)
    values(
      trim(p_book->>'title'), nullif(trim(p_book->>'original_title'),''), nullif(trim(p_book->>'romanized_title'),''),
      nullif(trim(p_book->>'author'),''), nullif(trim(p_book->>'contributors'),''), canonical,
      nullif(trim(p_book->>'series_name'),''), nullif(trim(p_book->>'volume_number'),''), nullif(trim(p_book->>'format'),''),
      nullif(trim(p_book->>'publisher'),''), nullif(trim(p_book->>'imprint'),''), nullif(trim(p_book->>'book_type'),''),
      nullif(trim(p_book->>'demographic'),''), nullif(trim(p_book->>'themes'),''), nullif(trim(p_book->>'age_rating'),''),
      nullif(trim(p_book->>'description'),''), nullif(trim(p_book->>'cover_image_url'),''), 'IN_LIBRARY'
    ) returning book_id into target_book_id;
    created_new := true;
    foreach genre_name in array coalesce(p_genres,'{}') loop
      if nullif(trim(genre_name),'') is not null then
        insert into public.book_genres(book_id,genre) values(target_book_id,trim(genre_name)) on conflict do nothing;
      end if;
    end loop;
  end if;

  if nullif(trim(p_barcode),'') is not null then
    insert into public.book_copies(book_id,identifier_value,identifier_type,shelf_id,status,condition_notes)
    values(target_book_id,trim(p_barcode),'BARCODE',p_shelf_id,'IN_SHELF',nullif(trim(p_condition_notes),''));
  elsif not created_new then
    raise exception 'A physical-copy barcode is required for an existing title';
  end if;

  return jsonb_build_object('book_id',target_book_id,'created_new',created_new);
end;
$$;

revoke all on function public.admin_create_catalog_entry(jsonb,text[],text,bigint,text) from public;
grant execute on function public.admin_create_catalog_entry(jsonb,text[],text,bigint,text) to authenticated;

commit;
