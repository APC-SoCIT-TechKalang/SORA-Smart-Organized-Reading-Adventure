create or replace function public.enforce_max_active_reading_logs()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  active_count integer;
begin
  if new.reading_status = 'READING' then
    select count(*)
      into active_count
      from public.reading_logs
     where visit_id = new.visit_id
       and reading_status = 'READING'
       and reading_log_id <> coalesce(new.reading_log_id, -1);

    if active_count >= 3 then
      raise exception 'A visit may have at most three actively logged books';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists reading_logs_max_active_trigger on public.reading_logs;
create trigger reading_logs_max_active_trigger
  before insert or update of visit_id, reading_status
  on public.reading_logs
  for each row
  execute function public.enforce_max_active_reading_logs();

create or replace function public.has_role(required_role text)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.profiles p
    join public.roles r on r.role_id = p.role_id
    where p.user_id = auth.uid()
      and p.is_active = true
      and r.name = required_role
  );
$$;

create or replace function public.is_active_member()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1
    from public.memberships m
    where m.user_id = auth.uid()
      and m.status = 'ACTIVE'
      and (m.expires_at is null or m.expires_at > now())
  );
$$;

